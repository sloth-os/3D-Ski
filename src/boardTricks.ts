function lesson(
  name: string,
  category: string,
  points: number,
  article: string,
  objective: string,
  movements: [string, string, string, string],
  drill: string,
  watch: string,
) {
  return {
    name,
    category: 'Snowboard · ' + category,
    points,
    source: library + article,
    objective,
    phases: movements.map((text, i) => [phases[i], text] as const),
    drill,
    watch,
    cue: drill,
    sidecut: 8.6,
    response: 0.87,
    edge: [23, 48] as const,
  }
}
